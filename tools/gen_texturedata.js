// Regenerates client/texturedata.js: the main color of every original texture (miptex in
// wads/*.wad and textures embedded in maps/*.bsp), measured by tools/texanalysis.js, and
// whether it repeats in lines. Never pixels: the game stays procedural and loads no
// texture files.
// deno run --allow-read --allow-write=client/texturedata.js tools/gen_texturedata.js

import { readWad, readBspTextures } from './wad.js';
import { RECORD_BYTES } from '../client/texcolors.js';

const ROOT = new URL('../', import.meta.url);
const OUT = new URL('client/texturedata.js', ROOT);

// Not world textures (HUD fonts and sprites, decals, sprays).
const SKIP_WADS = new Set(['decals.wad', 'fonts.wad', 'gfx.wad', 'spraypaint.wad', 'cached.wad']);
// On name clashes the earlier WAD wins: Counter-Strike's own, then Half-Life's.
const LAST_WADS = ['halflife.wad', 'xeno.wad'];
// Tool textures: never drawn.
const SKIP_NAMES = new Set(['sky', 'aaatrigger', 'clip', 'null', 'origin', 'hint', 'skip', 'bevel', 'noclip']);

function listDir(sub, ext) {
  try {
    return [...Deno.readDirSync(new URL(sub, ROOT))].map((e) => e.name).filter((n) => n.toLowerCase().endsWith(ext));
  } catch {
    return [];
  }
}

const wads = listDir('wads/', '.wad').filter((n) => !SKIP_WADS.has(n.toLowerCase()));
wads.sort((a, b) => {
  const ia = LAST_WADS.indexOf(a.toLowerCase()), ib = LAST_WADS.indexOf(b.toLowerCase());
  if (ia !== ib) return ia - ib;
  return a === 'cstrike.wad' ? -1 : b === 'cstrike.wad' ? 1 : a.localeCompare(b);
});

const textures = new Map();
const add = (t) => {
  if (!SKIP_NAMES.has(t.name) && !textures.has(t.name)) textures.set(t.name, t);
};
for (const w of wads) for (const t of readWad(Deno.readFileSync(new URL('wads/' + w, ROOT)))) add(t);
const fromWads = textures.size;
for (const m of listDir('maps/', '.bsp')) for (const t of readBspTextures(Deno.readFileSync(new URL('maps/' + m, ROOT)))) add(t);
console.log(`${fromWads} textures from ${wads.length} WADs, ${textures.size - fromWads} embedded in maps`);

// Analysis runs on one worker per core (tools/texworker.js).
const list = [...textures.values()].sort((a, b) => (a.name < b.name ? -1 : 1));
const threads = Math.max(1, Math.min(16, navigator.hardwareConcurrency || 4));
const chunks = Array.from({ length: threads }, (_, k) => list.filter((_t, i) => i % threads === k));
const results = await Promise.all(chunks.map((chunk) => new Promise((resolve, reject) => {
  const w = new Worker(new URL('./texworker.js', import.meta.url), { type: 'module' });
  w.onmessage = (e) => {
    w.terminate();
    resolve(e.data);
  };
  w.onerror = reject;
  w.postMessage(chunk);
})));
const names = [];
const records = [];
list.forEach((t, i) => {
  const rec = results[i % threads][Math.floor(i / threads)];
  if (!rec) return;
  names.push(t.name);
  records.push(rec);
});
const bytes = new Uint8Array(records.length * RECORD_BYTES);
records.forEach((r, i) => bytes.set(r, i * RECORD_BYTES));
let bin = '';
for (const b of bytes) bin += String.fromCharCode(b);

const src = `// Generated by tools/gen_texturedata.js from the CS 1.6 / Half-Life WADs and map-embedded
// textures. Do not edit. Measured colors only (no pixels): ${names.length} textures,
// ${RECORD_BYTES} bytes each (client/texcolors.js).
export const TEXTURE_NAMES = '${names.join(' ')}';
export const TEXTURE_COLORS = '${btoa(bin)}';
`;
Deno.writeTextFileSync(OUT, src);
console.log(`wrote ${names.length} textures, ${(src.length / 1024).toFixed(0)} KB`);
